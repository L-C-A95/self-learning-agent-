from __future__ import annotations

import re
from urllib.parse import unquote

from deepdive.models import Claim, ResearchReport

# Local-corpus chunks get a synthetic URL with no server behind it — clicking it
# gave a 404. Render the real file path instead, which the reader can open.
_CORPUS_RE = re.compile(r"^https?://localhost/corpus/([^#]+)")


def _render_source(cit, *, with_page: bool = True) -> str:
    """Readable reference for one citation."""
    page = getattr(cit, "page", None)
    page_note = f" · p.{page}" if (with_page and page) else ""
    match = _CORPUS_RE.match(str(cit.url))
    if match:
        return f"`{unquote(match.group(1))}`{page_note}"
    title = cit.title or "Untitled"
    return f"[{title}]({cit.url}){page_note}"


def report_to_markdown(report: ResearchReport, *, include_evidence: bool = True) -> str:
    """Render a ResearchReport as a self-contained Markdown document.

    When ``include_evidence`` is True (the default), an "Evidence" appendix
    lists every claim with its verbatim source excerpt — the citation-honesty
    contract is visible to the reader, not buried in a JSON trace.
    """
    lines: list[str] = []
    lines.append(f"# {report.question}\n")
    if report.summary:
        lines.append(report.summary.strip() + "\n")

    for section in report.sections:
        lines.append(f"## {section.heading}\n")
        _body = section.body.strip()
        _body = re.sub(
            r"^#{1,6}\s*" + re.escape(section.heading) + r"\s*\n?",
            "",
            _body,
            count=1,
            flags=re.IGNORECASE,
        ).strip()
        lines.append(_body + "\n")

    if report.sources:
        lines.append("## Sources\n")
        for i, src in enumerate(report.sources, 1):
            lines.append(f"{i}. {_render_source(src, with_page=False)}")
        lines.append("")

    all_claims: list[Claim] = []
    _seen_claim_keys: set[str] = set()
    for _section in report.sections:
        for _claim in _section.claims:
            _key = " ".join(_claim.text.lower().split())
            if _key in _seen_claim_keys:
                continue
            _seen_claim_keys.add(_key)
            all_claims.append(_claim)
    grounded = sum(1 for c in all_claims if c.grounded)
    total = len(all_claims)

    if include_evidence and total > 0:
        lines.append("## Evidence\n")
        lines.append(
            f"_{grounded}/{total} claims are span-grounded "
            "(verbatim excerpt verified against source)._\n"
        )
        for i, claim in enumerate(all_claims, 1):
            lines.append(f"**{i}.** {claim.text}")
            for cit in claim.citations:
                marker = "✓" if cit.grounded else "✗"
                lines.append(f"   - [{marker}] {_render_source(cit)}")
                if cit.excerpt:
                    excerpt = cit.excerpt.replace("\n", " ").strip()
                    if len(excerpt) > 240:
                        excerpt = excerpt[:237] + "…"
                    lines.append(f"     > {excerpt}")
            lines.append("")

    grounding_note = ""
    if total > 0:
        grounding_note = f" — {grounded}/{total} grounded"

    _dropped = getattr(report, "sentences_dropped", 0)
    audit_note = f" · 句子校验删去 {_dropped} 句无依据表述" if _dropped else ""

    lines.append(
        f"\n---\n*Generated by DeepDive at {report.generated_at.isoformat()}"
        f" — cost ${report.total_cost_usd:.4f} USD"
        f"{grounding_note}{audit_note}*"
    )
    return "\n".join(lines)


def _claim_status(claim: Claim) -> str:
    """Compact status marker for a claim. Public so other exporters can reuse."""
    return "grounded" if claim.grounded else "ungrounded"
